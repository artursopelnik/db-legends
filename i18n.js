const LANG_KEY = 'dbl-lang';
const SUPPORTED_LANGS = Object.keys(I18N);

function langFromPath() {
  if (typeof location === 'undefined') return null;
  const seg = location.pathname.split('/').filter(Boolean)[0];
  return seg && SUPPORTED_LANGS.includes(seg) ? seg : null;
}

function preferredLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
  } catch {}
  const langs = (typeof navigator !== 'undefined' && (navigator.languages || [navigator.language]))
    || ['en'];
  for (const tag of langs) {
    const base = String(tag || '').toLowerCase().split('-')[0];
    if (SUPPORTED_LANGS.includes(base)) return base;
  }
  return 'en';
}

function detectLang() {
  if (typeof window === 'undefined') return 'en';
  const fromPath = langFromPath();
  if (fromPath) return fromPath;
  return preferredLang();
}

let currentLang = detectLang();

// Root-Redirect: URL ist "/", aber Nutzer bevorzugt andere Sprache -> einmalige
// Weiterleitung pro Session, damit indexierte /-URL sauber bleibt.
(function maybeRedirectFromRoot() {
  if (typeof window === 'undefined' || typeof sessionStorage === 'undefined') return;
  if (langFromPath()) return;
  const pref = preferredLang();
  if (pref === 'en') return;
  try {
    if (sessionStorage.getItem('dbl-lang-redirected')) return;
    sessionStorage.setItem('dbl-lang-redirected', '1');
  } catch {}
  location.replace('/' + pref + '/' + location.search + location.hash);
})();

function langToPath(lang) {
  return lang === 'en' ? '/' : '/' + lang + '/';
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  currentLang = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

function navigateToLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang) || typeof location === 'undefined') return;
  const target = langToPath(lang);
  const current = langToPath(langFromPath() || 'en');
  if (target === current) return;
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
  location.assign(target + location.search + location.hash);
}

function t(key, vars) {
  let str = (I18N[currentLang] && I18N[currentLang][key]) || I18N.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace('{' + k + '}', v);
    }
  }
  return str;
}

// Interne Links auf die aktive Sprachversion umbiegen: die Root-Seite wird
// clientseitig uebersetzt (z. B. PWA-Start auf "/" mit deutscher Sprache),
// ihre statischen Links zeigen aber auf die englischen Unterseiten.
const LOCALIZED_SECTIONS = ['teams', 'blog', 'promo-codes'];

function localizeHref(href, lang) {
  const langAlt = SUPPORTED_LANGS.filter((l) => l !== 'en').join('|');
  const m = href.match(new RegExp('^\\/(?:(' + langAlt + ')\\/)?([^#?]*)([#?].*)?$'));
  if (!m) return href;
  const rest = m[2] || '';
  const suffix = m[3] || '';
  if (rest !== '' && !LOCALIZED_SECTIONS.includes(rest.split('/')[0])) return href;
  return (lang === 'en' ? '/' : '/' + lang + '/') + rest + suffix;
}

// Uebertraegt alle data-i18n-Attribute (Text, Placeholder, Alt) in den DOM.
function applyStaticTranslations() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('a[href^="/"]').forEach((el) => {
    el.setAttribute('href', localizeHref(el.getAttribute('href'), currentLang));
  });
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    let vars;
    if (el.dataset.i18nVars) {
      try { vars = JSON.parse(el.dataset.i18nVars); } catch {}
    }
    el.textContent = t(el.dataset.i18n, vars);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
    el.alt = t(el.dataset.i18nAlt);
  });
  const sel = document.getElementById('langSelect');
  if (sel) sel.value = currentLang;
}

